import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, statSync } from "node:fs";
import { dirname, extname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sha256 = (value) => createHash("sha256").update(value).digest("hex");
const readJson = (path) => JSON.parse(readFileSync(resolve(root, path), "utf8"));
const failures = [];
const fail = (message) => failures.push(message);
const required = [
  "README.md",
  "LICENSE",
  "SECURITY.md",
  "CONTRIBUTING.md",
  "CODE_OF_CONDUCT.md",
  "SUPPORT.md",
  "GOVERNANCE.md",
  "DISCLAIMER.md",
  "CITATION.cff",
  "CHANGELOG.md",
  "FORMAL_VERIFICATION.md",
  ".github/CODEOWNERS",
  ".github/PULL_REQUEST_TEMPLATE.md",
  ".github/dependabot.yml",
  ".github/workflows/ci.yml",
  ".github/workflows/identity.yml",
  "docs/PROOF-BOUND-IDENTIFIERS.md",
  "evidence/current-profile-release-index-v1.json",
  "evidence/current-profile-release-index-v2.json",
  "evidence/public-release/diet-manifest-v1.json",
  "evidence/public-release/proof-bound-identifiers-v1.json",
  "evidence/public-release/supersession-manifest-v1.json",
  "evidence/public-release/formal-foundation-supersession-v1.json",
  "formal-dependencies-public-v1.lock.json",
  "scripts/replay-current-profile-release.ps1",
  "scripts/verify-current-profile-release.mjs",
  "scripts/verify-current-profile-release-v2.mjs",
  "scripts/verify-formal-foundation-supersession.mjs",
];
for (const path of required) if (!existsSync(resolve(root, path))) fail(`missing required public file: ${path}`);

const tracked = execFileSync("git", ["ls-files", "-z"], { cwd: root, encoding: "utf8" })
  .split("\0").filter(Boolean);
const present = tracked.filter((path) => existsSync(resolve(root, path)));
const diet = readJson("evidence/public-release/diet-manifest-v1.json");
const allowlist = readJson("evidence/public-release/proof-bound-identifiers-v1.json");
const supersession = readJson("evidence/public-release/supersession-manifest-v1.json");
if (diet.kind !== "ERC_TRUST_PUBLIC_TREE_DIET_MANIFEST_V1") fail("diet manifest identity drift");
if (allowlist.kind !== "ERC_TRUST_PROOF_BOUND_HISTORICAL_IDENTIFIERS_V1") fail("proof-bound allowlist identity drift");
if (supersession.kind !== "ERC_TRUST_PUBLIC_RELEASE_SUPERSESSION_MANIFEST_V1") fail("supersession manifest identity drift");
for (const entry of diet.removedFiles) {
  if (existsSync(resolve(root, entry.path))) fail(`archive-only path remains: ${entry.path}`);
}

const internalPattern = /\b(?:M[1-9]\d*|G[1-9]\d*|FV\d+)\b/g;
const pathInternalPattern = /^(?:m[1-9]\d*|g[1-9]\d*|fv\d+)(?:$|[-_.])/i;
const allowed = new Map(allowlist.files.map((entry) => [entry.path, entry]));
for (const entry of allowlist.files) {
  const absolute = resolve(root, entry.path);
  if (!existsSync(absolute)) {
    fail(`proof-bound allowlist path missing: ${entry.path}`);
    continue;
  }
  const value = readFileSync(absolute);
  const text = value.toString("utf8");
  internalPattern.lastIndex = 0;
  const count = [...text.matchAll(internalPattern)].length;
  internalPattern.lastIndex = 0;
  if (sha256(value) !== entry.sha256) fail(`proof-bound byte drift: ${entry.path}`);
  if (count !== entry.contentOccurrenceCount) fail(`proof-bound occurrence drift: ${entry.path}`);
}

const lifecycleExclusions = new Set([
  "docs/PROOF-BOUND-IDENTIFIERS.md",
  "evidence/public-release/diet-manifest-v1.json",
  "evidence/public-release/proof-bound-identifiers-v1.json",
  "evidence/public-release/supersession-manifest-v1.json",
  "scripts/verify-public-release-tree.mjs",
  "scripts/verify-public-surface.mjs",
  "scripts/verify-repository-health.mjs",
]);
const selfScanningExclusions = new Set([
  "scripts/verify-public-release-tree.mjs",
  "scripts/verify-public-surface.mjs",
  "scripts/verify-repository-health.mjs",
]);
const textExtensions = new Set([".cff", ".conf", ".json", ".jsonl", ".k", ".md", ".mjs", ".ps1", ".py", ".sh", ".sol", ".spec", ".tex", ".thy", ".toml", ".ts", ".yaml", ".yml"]);
const localCoordinatePattern = /(?:C:[/\\](?:Users|tmp)[/\\]|\/cygdrive\/c\/(?:Users|tmp)\/|\/mnt\/c\/(?:Users|tmp)\/|\/Users\/[^/]+\/|\/home\/(?!runner(?:\/|$))[^/]+\/)/i;
const credentialPattern = /(?:CERTORAKEY\s*[:=]\s*[A-Za-z0-9_-]{12,}|AKIA[0-9A-Z]{16}|arn:aws|gh[pousr]_[A-Za-z0-9_]{16,}|-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----)/;
const attributionPattern = /\b(?:ChatGPT|OpenAI|Anthropic|Claude|Codex)\b|AI[- ]generated|generated by AI/i;
for (const path of present) {
  const absolute = resolve(root, path);
  if (absolute.length >= 240) fail(`overlong tracked path (${absolute.length}): ${path}`);
  const extension = extname(path).toLowerCase();
  if (!textExtensions.has(extension)) continue;
  const value = readFileSync(absolute);
  if (value.includes(0)) continue;
  const text = value.toString("utf8");
  if (extension === ".json") {
    try { JSON.parse(text); } catch (error) { fail(`invalid JSON: ${path}: ${error.message}`); }
  }
  if (!selfScanningExclusions.has(path)) {
    if (localCoordinatePattern.test(text)) fail(`private absolute coordinate: ${path}`);
    if (credentialPattern.test(text)) fail(`credential-like content: ${path}`);
    if (attributionPattern.test(text)) fail(`tool attribution: ${path}`);
    if (/\b(?:codex|claude)\//i.test(text)) fail(`private branch identifier: ${path}`);
  }
  if (extension === ".md" && (text.includes("—") || text.includes("–"))) fail(`dash punctuation: ${path}`);
  if (!lifecycleExclusions.has(path) && !allowed.has(path) && internalPattern.test(text)) {
    fail(`unallowlisted lifecycle identifier: ${path}`);
  }
  internalPattern.lastIndex = 0;
  if (!lifecycleExclusions.has(path) && !allowed.has(path)
      && path.split("/").some((segment) => pathInternalPattern.test(segment))) {
    fail(`unallowlisted lifecycle identifier in path: ${path}`);
  }
}

const forbiddenPathPatterns = [
  /(^|\/)save(\/|$)/,
  /(^|\/)artifacts(\/|$)/,
  /(^|\/)certora-current-profile\/jobs(\/|$)/,
  /(^|\/)failed-probes(\/|$)/,
  /(^|\/)run-ledger\.jsonl$/,
  /(^|\/)proof-run-ledger\.json$/,
  /formal\/isabelle\/.+\/release\/.+\.pdf$/,
];
for (const path of present) {
  if (forbiddenPathPatterns.some((pattern) => pattern.test(path))) fail(`forbidden raw/process path: ${path}`);
}

const readme = readFileSync(resolve(root, "README.md"), "utf8");
const firstThirty = readme.split("\n").slice(0, 30).join("\n");
if (!firstThirty.includes("Unaudited. Not for production.")) fail("README warning is not in the first 30 lines");
const badgeCount = (firstThirty.match(/\[!\[/g) ?? []).length;
if (badgeCount !== 6) fail(`README badge count drift: ${badgeCount}`);
if (!readme.includes("scripts/replay-current-profile-release.ps1")) fail("public replay command missing from README");
const attributes = readFileSync(resolve(root, ".gitattributes"), "utf8");
if (!attributes.includes("**/generated/** linguist-generated=true")
    || !attributes.includes("**/mutant-runtime-bridge.k linguist-generated=true")) {
  fail("generated-source Linguist mapping missing");
}
if (present.length !== diet.summary.retainedFiles) fail(`retained path count drift: ${present.length}`);

if (failures.length) {
  for (const failure of failures) console.error(failure);
  process.exit(1);
}
const bytes = present.reduce((sum, path) => sum + statSync(resolve(root, path)).size, 0);
console.log(JSON.stringify({
  status: "PASS_PUBLIC_RELEASE_TREE",
  trackedFiles: present.length,
  trackedBytes: bytes,
  archivedFiles: diet.summary.removedFiles,
  archivedBytes: diet.summary.removedBytes,
  proofBoundFiles: allowlist.summary.files,
  proofBoundOccurrences: allowlist.summary.contentOccurrences,
  privateCoordinates: 0,
  privateBranches: 0,
  toolAttribution: 0,
  dashPunctuation: 0,
  overlongPaths: 0,
}, null, 2));
